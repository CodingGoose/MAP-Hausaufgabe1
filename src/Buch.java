public class Buch {
    private String Titel;
    private String Autor;
    private float Preis;
    private int AnzahlSeiten;

    public String getTitel(){
        return this.Titel;
    }

    public String getAutor() {
        return Autor;
    }

    public float getPreis() {
        return Preis;
    }

    public int getAnzahlSeiten() {
        return AnzahlSeiten;
    }
}
